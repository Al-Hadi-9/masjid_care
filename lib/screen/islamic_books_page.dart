  Widget _buildChapterReader(Map<String, dynamic> book, int chapterIdx) {
    final chapters = (book["chapters"] as List).cast<Map<String, dynamic>>();
    final chapter = chapters[chapterIdx];
    final paragraphs = (chapter["content"] as List).cast<String>();
    return Scaffold(
      backgroundColor: const Color(0xFFF8F9FA),
      appBar: AppAppBar(
        title: AppAppBar.kMasjidName,
        subtitle: book["title"]!,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back, color: Colors.white),
          onPressed: () => setState(() => _selectedChapterIndex = null),
        ),
        actions: [
          IconButton(
            icon: const Icon(Icons.list, color: Colors.white),
            tooltip: Tr.booksBackToList(context),
            onPressed: () => setState(() {
              _selectedBookIndex = null;
              _selectedChapterIndex = null;
            }),
          ),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.all(12),
        children: [
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: const Color(0xFFE8F5E9),
              borderRadius: BorderRadius.circular(14),
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    Container(
                      padding: const EdgeInsets.symmetric(
                        horizontal: 10,
                        vertical: 4,
                      ),
                      decoration: BoxDecoration(
                        color: const Color(0xFF1B5E4E),
                        borderRadius: BorderRadius.circular(8),
                      ),
                      child: Text(
                        '${Tr.booksChapterLabel(context)}${chapterIdx + 1}',
                        style: const TextStyle(
                          color: Colors.white,
                          fontSize: 12,
                          fontWeight: FontWeight.bold,
                        ),
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 10),
                Text(
                  chapter["title"]!,
                  style: const TextStyle(
                    fontSize: 18,
                    fontWeight: FontWeight.bold,
                    color: Color(0xFF2C3E50),
                  ),
                ),
              ],
            ),
          ),
          const SizedBox(height: 12),
          ...paragraphs.map(
            (p) => Container(
              margin: const EdgeInsets.only(bottom: 10),
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(12),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withValues(alpha: 0.03),
                    blurRadius: 4,
                    offset: const Offset(0, 2),
                  ),
                ],
              ),
              child: Text(
                p,
                style: const TextStyle(
                  fontSize: 14,
                  color: Color(0xFF34495E),
                  height: 1.8,
                ),
              ),
            ),
          ),
          const SizedBox(height: 8),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              if (chapterIdx > 0)
                ElevatedButton.icon(
                  onPressed: () =>
                      setState(() => _selectedChapterIndex = chapterIdx - 1),
                  icon: const Icon(Icons.arrow_back, size: 16),
                  label: Text(Tr.booksPrev(context)),
                  style: ElevatedButton.styleFrom(
                    backgroundColor: const Color(0xFF1B5E4E),
                    foregroundColor: Colors.white,
                  ),
                )
              else
                const SizedBox.shrink(),
              if (chapterIdx < chapters.length - 1)
                ElevatedButton.icon(
                  onPressed: () =>
                      setState(() => _selectedChapterIndex = chapterIdx + 1),
                  icon: const Icon(Icons.arrow_forward, size: 16),
                  label: Text(Tr.booksNext(context)),
                  style: ElevatedButton.styleFrom(
                    backgroundColor: const Color(0xFF1B5E4E),
                    foregroundColor: Colors.white,
                  ),
                )
              else
                const SizedBox.shrink(),
            ],
          ),
          const SizedBox(height: 16),
          Center(
            child: Container(
              padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 10),
              decoration: BoxDecoration(
                color: const Color(0xFFE8F5E9),
                borderRadius: BorderRadius.circular(10),
              ),
              child: Text(
                Tr.booksAllPraise(context),
                style: const TextStyle(
                  color: Color(0xFF1B5E4E),
                  fontWeight: FontWeight.bold,
                ),
              ),
            ),
          ),
        ],
      ),
    );
  }
