  @override
  Widget build(BuildContext context) {
    // Subscribe to language toggle so list/reader chrome flips.
    SettingsScope.of(context);

    if (_selectedBookIndex != null) {
      if (_selectedChapterIndex != null) {
        return _buildChapterReader(
          _bookList[_selectedBookIndex!],
          _selectedChapterIndex!,
        );
      }
      return _buildBookReader(_bookList[_selectedBookIndex!]);
    }
    return Scaffold(
      backgroundColor: const Color(0xFFF0F4F7),
      appBar: AppAppBar(
        title: AppAppBar.kMasjidName,
        subtitle: 'ইসলামী বই',
        leading: IconButton(
          icon: const Icon(Icons.arrow_back, color: Colors.white),
          onPressed: () => Navigator.pop(context),
        ),
      ),
      body: Column(
        children: [
          Container(
            color: Colors.white,
            padding: const EdgeInsets.all(16),
            child: Row(
              children: [
                Container(
                  width: 5,
                  height: 25,
                  decoration: BoxDecoration(
                    color: const Color(0xFF1B5E4E),
                    borderRadius: BorderRadius.circular(2),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Text(
                    Tr.booksListLabel(context),
                    style: const TextStyle(
                      fontSize: 18,
                      fontWeight: FontWeight.bold,
                      color: Color(0xFF2C3E50),
                    ),
                  ),
                ),
              ],
            ),
          ),
          Expanded(child: _buildBookList()),
        ],
      ),
    );
  }

  Widget _buildBookList() {
    return ListView.builder(
      padding: const EdgeInsets.all(12),
      itemCount: _bookList.length,
      itemBuilder: (context, i) {
        final b = _bookList[i];
        return Card(
          elevation: 1,
          margin: const EdgeInsets.symmetric(vertical: 6),
          shape: RoundedRectangleBorder(
            borderRadius: BorderRadius.circular(14),
          ),
          child: ListTile(
            contentPadding: const EdgeInsets.symmetric(
              horizontal: 14,
              vertical: 8,
            ),
            leading: CircleAvatar(
              radius: 24,
              backgroundColor: const Color(0xFF1B5E4E),
              foregroundColor: Colors.white,
              child: Text(
                b["num"]!,
                style: const TextStyle(
                  fontSize: 16,
                  fontWeight: FontWeight.bold,
                ),
              ),
            ),
            title: Text(
              b["title"]!,
              style: const TextStyle(
                fontWeight: FontWeight.bold,
                fontSize: 15,
                color: Color(0xFF2C3E50),
              ),
            ),
            subtitle: Padding(
              padding: const EdgeInsets.only(top: 4),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    b["author"]!,
                    style: const TextStyle(
                      fontSize: 12,
                      color: Color(0xFF1B5E4E),
                      fontWeight: FontWeight.w600,
                    ),
                  ),
                  const SizedBox(height: 2),
                  Text(
                    b["desc"]!,
                    style: const TextStyle(fontSize: 12, color: Colors.grey),
                  ),
                ],
              ),
            ),
            trailing: const Icon(
              Icons.arrow_forward_ios,
              size: 16,
              color: Color(0xFF1B5E4E),
            ),
            onTap: () => setState(() => _selectedBookIndex = i),
          ),
        );
      },
    );
  }

  Widget _buildBookReader(Map<String, dynamic> book) {
    final chapters = (book["chapters"] as List).cast<Map<String, dynamic>>();
    return Scaffold(
      backgroundColor: const Color(0xFFF8F9FA),
      appBar: AppAppBar(
        title: AppAppBar.kMasjidName,
        subtitle: book["title"]!,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back, color: Colors.white),
          onPressed: () => setState(() => _selectedBookIndex = null),
        ),
        actions: [
          IconButton(
            icon: const Icon(Icons.list, color: Colors.white),
            tooltip: Tr.booksBackToList(context),
            onPressed: () => setState(() {
              _selectedBookIndex = null;
              _selectedChapterIndex = null;
            }),
          ),
        ],
      ),
      body: ListView(
        padding: const EdgeInsets.all(12),
        children: [
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: Colors.white,
              borderRadius: BorderRadius.circular(14),
              boxShadow: [
                BoxShadow(
                  color: Colors.black.withValues(alpha: 0.04),
                  blurRadius: 6,
                  offset: const Offset(0, 2),
                ),
              ],
            ),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    CircleAvatar(
                      backgroundColor: const Color(0xFF1B5E4E),
                      foregroundColor: Colors.white,
